module fp12_mul(input wire [11:0] a,b, output reg [11:0] y);
wire signbit=a[11]^b[11];
wire [4:0] ea=a[10:6], eb=b[10:6];
wire [5:0] fa=a[5:0], fb=b[5:0];
wire [5:0] ax=ea==0?6'd1:{1'b0,ea}, bx=eb==0?6'd1:{1'b0,eb};
wire [6:0] es={1'b0,ax}+{1'b0,bx};
wire [6:0] ma={ea!=0,fa}, mb={eb!=0,fb};
wire [13:0] p;
assign p = ma * mb;
reg [3:0] k;
reg signed [6:0] ex;
reg [7:0] nq,sq,q;
reg [10:0] magnitude;
always @* begin
k=0; casez(p)
14'b1?????????????: k=4'd13;
14'b01????????????: k=4'd12;
14'b001???????????: k=4'd11;
14'b0001??????????: k=4'd10;
14'b00001?????????: k=4'd9;
14'b000001????????: k=4'd8;
14'b0000001???????: k=4'd7;
14'b00000001??????: k=4'd6;
14'b000000001?????: k=4'd5;
14'b0000000001????: k=4'd4;
14'b00000000001???: k=4'd3;
14'b000000000001??: k=4'd2;
14'b0000000000001?: k=4'd1;
14'b00000000000001: k=4'd0;
default:k=0; endcase
ex=$signed(es)+$signed({3'b0,k})-7'sd27;
nq=0; sq=0;
case(k)
4'd6: nq={1'b0,p[6:0]};
4'd7: nq=8'((p >> 1) + (p[0] & (1'b0|p[1])));
4'd8: nq=8'((p >> 2) + (p[1] & ((|p[0:0])|p[2])));
4'd9: nq=8'((p >> 3) + (p[2] & ((|p[1:0])|p[3])));
4'd10: nq=8'((p >> 4) + (p[3] & ((|p[2:0])|p[4])));
4'd11: nq=8'((p >> 5) + (p[4] & ((|p[3:0])|p[5])));
4'd12: nq=8'((p >> 6) + (p[5] & ((|p[4:0])|p[6])));
4'd13: nq=8'((p >> 7) + (p[6] & ((|p[5:0])|p[7])));
default:nq=0; endcase
case(es)
7'd8: sq=8'((p >> 14) + (p[13] & ((|p[12:0])|1'b0)));
7'd9: sq=8'((p >> 13) + (p[12] & ((|p[11:0])|p[13])));
7'd10: sq=8'((p >> 12) + (p[11] & ((|p[10:0])|p[12])));
7'd11: sq=8'((p >> 11) + (p[10] & ((|p[9:0])|p[11])));
7'd12: sq=8'((p >> 10) + (p[9] & ((|p[8:0])|p[10])));
7'd13: sq=8'((p >> 9) + (p[8] & ((|p[7:0])|p[9])));
7'd14: sq=8'((p >> 8) + (p[7] & ((|p[6:0])|p[8])));
7'd15: sq=8'((p >> 7) + (p[6] & ((|p[5:0])|p[7])));
7'd16: sq=8'((p >> 6) + (p[5] & ((|p[4:0])|p[6])));
7'd17: sq=8'((p >> 5) + (p[4] & ((|p[3:0])|p[5])));
7'd18: sq=8'((p >> 4) + (p[3] & ((|p[2:0])|p[4])));
7'd19: sq=8'((p >> 3) + (p[2] & ((|p[1:0])|p[3])));
7'd20: sq=8'((p >> 2) + (p[1] & ((|p[0:0])|p[2])));
7'd21: sq=8'((p >> 1) + (p[0] & (1'b0|p[1])));
7'd22: sq={1'b0,p[6:0]};
default:sq=0; endcase
q=ex<1?sq:nq;
if(ex<1) ex=1;
if(q[7]) begin q=q>>1; ex=ex+1; end
if(ex>=31) magnitude=11'h7c0;
else if(ex==1 && !q[6]) magnitude={5'b0,q[5:0]};
else magnitude={ex[4:0],q[5:0]};
y={signbit,magnitude};
if(a[10:0]==0 || b[10:0]==0) y={signbit,11'b0};
if(ea==31 || eb==31) y={signbit,11'h7c0};
if((ea==31 && fa!=0)||(eb==31 && fb!=0)||
(ea==31 && b[10:0]==0)||(eb==31 && a[10:0]==0)) y=12'h7e0;
end
endmodule
