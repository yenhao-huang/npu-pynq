module fp12_mul(input wire [11:0] a,b, output reg [11:0] y);
wire signbit=a[11]^b[11];
wire [4:0] ea=a[10:6], eb=b[10:6];
wire [5:0] fa=a[5:0], fb=b[5:0];
wire [5:0] ax=ea==0?6'd1:{1'b0,ea}, bx=eb==0?6'd1:{1'b0,eb};
wire [6:0] es={1'b0,ax}+{1'b0,bx};
wire [6:0] ma={ea!=0,fa}, mb={eb!=0,fb};
wire [13:0] p;
wire [13:0] r0 = ({7'b0,ma} << 0) & {14{mb[0]}};
wire [13:0] r1 = ({7'b0,ma} << 1) & {14{mb[1]}};
wire [13:0] r2 = ({7'b0,ma} << 2) & {14{mb[2]}};
wire [13:0] r3 = ({7'b0,ma} << 3) & {14{mb[3]}};
wire [13:0] r4 = ({7'b0,ma} << 4) & {14{mb[4]}};
wire [13:0] r5 = ({7'b0,ma} << 5) & {14{mb[5]}};
wire [13:0] r6 = ({7'b0,ma} << 6) & {14{mb[6]}};
assign p = r0+r1+r2+r3+r4+r5+r6;
reg [3:0] k;
reg signed [6:0] ex;
reg [6:0] nf,sf,f;
reg [10:0] mag,unrounded;
always @* begin
k=0; casez(p)
14'b1?????????????: k=4'd13;
14'b01????????????: k=4'd12;
14'b001???????????: k=4'd11;
14'b0001??????????: k=4'd10;
14'b00001?????????: k=4'd9;
14'b000001????????: k=4'd8;
14'b0000001???????: k=4'd7;
14'b00000001??????: k=4'd6;
14'b000000001?????: k=4'd5;
14'b0000000001????: k=4'd4;
14'b00000000001???: k=4'd3;
14'b000000000001??: k=4'd2;
14'b0000000000001?: k=4'd1;
14'b00000000000001: k=4'd0;
default:k=0; endcase
ex=$signed(es)+$signed({3'b0,k})-7'sd27;
nf=0;sf=0;
case(k)
4'd6:nf={p[5:0],1'b0};
4'd7:nf={6'(p >> 1), (p[0] & (1'b0|p[1]))};
4'd8:nf={6'(p >> 2), (p[1] & ((|p[0:0])|p[2]))};
4'd9:nf={6'(p >> 3), (p[2] & ((|p[1:0])|p[3]))};
4'd10:nf={6'(p >> 4), (p[3] & ((|p[2:0])|p[4]))};
4'd11:nf={6'(p >> 5), (p[4] & ((|p[3:0])|p[5]))};
4'd12:nf={6'(p >> 6), (p[5] & ((|p[4:0])|p[6]))};
4'd13:nf={6'(p >> 7), (p[6] & ((|p[5:0])|p[7]))};
default:nf=0;endcase
case(es)
7'd8:sf={6'(p >> 14), (p[13] & ((|p[12:0])|1'b0))};
7'd9:sf={6'(p >> 13), (p[12] & ((|p[11:0])|p[13]))};
7'd10:sf={6'(p >> 12), (p[11] & ((|p[10:0])|p[12]))};
7'd11:sf={6'(p >> 11), (p[10] & ((|p[9:0])|p[11]))};
7'd12:sf={6'(p >> 10), (p[9] & ((|p[8:0])|p[10]))};
7'd13:sf={6'(p >> 9), (p[8] & ((|p[7:0])|p[9]))};
7'd14:sf={6'(p >> 8), (p[7] & ((|p[6:0])|p[8]))};
7'd15:sf={6'(p >> 7), (p[6] & ((|p[5:0])|p[7]))};
7'd16:sf={6'(p >> 6), (p[5] & ((|p[4:0])|p[6]))};
7'd17:sf={6'(p >> 5), (p[4] & ((|p[3:0])|p[5]))};
7'd18:sf={6'(p >> 4), (p[3] & ((|p[2:0])|p[4]))};
7'd19:sf={6'(p >> 3), (p[2] & ((|p[1:0])|p[3]))};
7'd20:sf={6'(p >> 2), (p[1] & ((|p[0:0])|p[2]))};
7'd21:sf={6'(p >> 1), (p[0] & (1'b0|p[1]))};
7'd22:sf={p[5:0],1'b0};
default:sf=0;endcase
f=ex<1?sf:nf;
unrounded={ex<1?5'b0:ex[4:0],f[6:1]};
mag=unrounded+{10'b0,f[0]};
if(ex>=31)mag=11'h7c0;
y={signbit,mag};
if(a[10:0]==0 || b[10:0]==0)y={signbit,11'b0};
if(ea==31 || eb==31)y={signbit,11'h7c0};
if((ea==31 && fa!=0)||(eb==31 && fb!=0)||
(ea==31 && b[10:0]==0)||(eb==31 && a[10:0]==0))y=12'h7e0;
end
endmodule
