"""Copy the designs behind the largest multi-round PPA improvements into docs/acceptance/improvement/.

For each model's top cases in evidence/multi_round_analysis.json, this collects the best
candidate of all three arms — baseline, single-round, multi-round — as byte-identical
copies, so they can be diffed and re-synthesized. Provenance and measurements go in the
generated READMEs; the RTL itself is never annotated.

Run from exp/ab_test/:  python3 analysis/collect_improvement_cases.py [model ...]
"""
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = Path(os.environ.get("AB_RESULTS", ROOT.parent / "results")).resolve()  # local run archive by default
OUT = ROOT.parent / "docs" / "acceptance" / "improvement"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT.parent))
from analyze import load, MODELS  # noqa: E402
from multi_round_analysis import derived_clocks  # noqa: E402
from src.grade.pareto import eligible  # noqa: E402

ARMS = ("baseline", "single-round", "multi-round")
FOLDERS = {"claude-opus-5-5": "opus5.5", "claude-sonnet-5-5": "sonnet5.5", "gpt-6-sol": "gpt6-sol"}
# A clean round worth keeping beside a flagged best. (model, problem) -> (round, reason).
CLEAN_ALTERNATIVES = {
    ("claude-opus-5-5", "JC_counter"): (4, "same 64 -> 7 flop re-encoding, fully synchronous"),
}


def best(model, arm, problem):
    """The lowest-PDAP valid candidate of one arm on one problem, with its source file."""
    found = None
    for row in load(model, arm)[1]:
        if row["problem"] != problem or row["_api_error"]:
            continue
        for grade in row["per_round"]:
            if not eligible(grade):
                continue
            pdap = grade["power_w"] * grade["delay_ns"] * grade["area_um2"]
            if found is None or pdap < found["pdap"]:
                found = dict(pdap=pdap, rep=row["rep"], round=grade["round"],
                             source=row["_dir"] / f"round{grade['round']}.v",
                             **{k: grade[k] for k in ("area_um2", "power_w", "delay_ns")})
    return found


def at_round(model, problem, number):
    """One specific round of the selected multi-round attempt."""
    for row in load(model, "multi-round")[1]:
        if row["problem"] != problem or row["_api_error"]:
            continue
        grade = next((g for g in row["per_round"] if g["round"] == number), None)
        if grade and eligible(grade):
            return dict(pdap=grade["power_w"] * grade["delay_ns"] * grade["area_um2"],
                        rep=row["rep"], round=number,
                        source=row["_dir"] / f"round{number}.v",
                        **{k: grade[k] for k in ("area_um2", "power_w", "delay_ns")})
    return None


def collect(model, cases, folder):
    """Write one model's case folders and its README; return (case rows, flagged problems)."""
    lines = [f"# Largest multi-round PPA improvements: `{model}`", "",
             "The best design each arm reached on the five problems where multi-round beat",
             "single-round by the most, copied verbatim from the run records so they can be",
             "diffed and re-synthesized. Ratio is multi-round best PDAP over single-round best,",
             "lower being better; `PDAP = power_w x delay_ns x area_um2`.", "",
             "Generated by `analysis/collect_improvement_cases.py`. Analysis and method notes:",
             "[../../../multi-round-analysis.md](../../../multi-round-analysis.md)."]
    index, flagged = [], []
    for case in cases:
        problem = case["problem"]
        (folder / problem).mkdir(parents=True)
        rows = []
        for arm in ARMS:
            candidate = best(model, arm, problem)
            if candidate is None:
                continue
            shutil.copyfile(candidate["source"], folder / problem / f"{arm}.v")
            rows.append((f"{arm}.v", candidate,
                         derived_clocks((folder / problem / f"{arm}.v").read_text())))
        extra = CLEAN_ALTERNATIVES.get((model, problem))
        if extra and (candidate := at_round(model, problem, extra[0])):
            shutil.copyfile(candidate["source"], folder / problem / "multi-round-clean.v")
            rows.append(("multi-round-clean.v", candidate, []))

        mark = " :warning:" if any(r[2] for r in rows) else ""
        index.append(f"| [`{problem}`](./{problem}/){mark} | {case['ratio']:.3f}x | "
                     f"round {case['best_round']} | {', '.join(f'`{r[0]}`' for r in rows)} |")
        lines += ["", f"## `{problem}` — {case['ratio']:.3f}x{mark}", "",
                  "| File | PDAP | area um2 | power W | delay ns | Source |", "|---|---|---|---|---|---|"]
        lines += [f"| `{name}` | {c['pdap']:.3e} | {c['area_um2']:.2f} | {c['power_w']:.2e} | "
                  f"{c['delay_ns']:.3f} | `evidence/{c['source'].relative_to(DATA)}` |"
                  for name, c, _ in rows]
        if extra:
            lines += ["", f"`multi-round-clean.v` is round {extra[0]}: {extra[1]}. "
                          "It is kept because the best-PDAP round is flagged below."]
        bad = {name: clocks for name, _, clocks in rows if clocks}
        if bad:
            flagged.append(problem)
            lines += ["", "> :warning: Generated clocks, so the `ppa` numbers are optimistic — "
                          "OpenROAD times only the primary clock here. "
                          + "; ".join(f"`{n}` clocks state off {', '.join('`%s`' % c for c in v)}"
                                      for n, v in bad.items())]

    insert = [i for i, line in enumerate(lines) if line.startswith("[../../../")][0] + 1
    lines[insert:insert] = ["", "| Case | Ratio | Best at | Files |", "|---|---|---|---|"] + index
    lines += ["", "## Reading these", "",
              "`baseline.v` had no IC tools; `single-round.v` had the same tools as",
              "`multi-round.v` but one turn. Where baseline and single-round are identical,",
              "that is the measured result, not a copy error — independent attempts on these",
              "problems converge on the same design."]
    if flagged:
        lines += ["", f"Flagged cases ({', '.join('`%s`' % p for p in flagged)}) win partly by",
                  "moving state onto internally generated clocks, which this PPA flow does not",
                  "time. Do not quote them as PPA results without that caveat."]
    lines.append("")
    (folder / "README.md").write_text("\n".join(lines))
    return index, flagged


def main():
    models = sys.argv[1:] or MODELS
    analysis = json.loads((DATA / "multi_round_analysis.json").read_text())
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    top = ["# Largest multi-round PPA improvements", "",
           "One folder per model. Each holds, for the five problems where multi-round beat",
           "single-round by the most, the best design of all three arms — copied verbatim from",
           "the run records, so they compile and re-synthesize as they were measured.", "",
           "Generated by `analysis/collect_improvement_cases.py`; rerun it to rebuild this tree.",
           "Analysis and method notes: [../../multi-round-analysis.md](../../multi-round-analysis.md).",
           "", "| Model | Cases | Flagged |", "|---|---|---|"]
    for model in models:
        folder = OUT / FOLDERS[model]
        index, flagged = collect(model, analysis[model]["top"], folder)
        top.append(f"| [`{model}`](./{FOLDERS[model]}/) | {len(index)} | "
                   + (", ".join(f"`{p}`" for p in flagged) if flagged else "none") + " |")
    top += ["", ":warning: marks a case whose winning design clocks state off an internally",
            "generated signal. This PPA flow times only the primary clock, so its delay and",
            "power are optimistic.", ""]
    (OUT / "README.md").write_text("\n".join(top))

    print(f"{len(models)} models -> {OUT.relative_to(ROOT.parent)}")
    for path in sorted(OUT.rglob("*")):
        print(f"  {path.relative_to(OUT)}")


if __name__ == "__main__":
    main()
